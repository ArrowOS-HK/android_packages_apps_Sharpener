package com.arrow.support.provider;

import android.content.ContentProvider;
import android.content.ContentValues;
import android.content.Context;
import android.database.Cursor;
import android.net.Uri;
import android.os.ParcelFileDescriptor;

import java.io.File;
import java.io.FileNotFoundException;

/**
 * Exposes Sharpener's saved Extended QS custom image/GIF read-only to SystemUI
 * without relying on fragile temporary document URI grants.
 */
public class InvCustomImageProvider extends ContentProvider {

    public static final String AUTHORITY = "com.android.settings.qsimage";
    public static final String FILE_NAME = "invqs_custom_image.bin";

    @Override
    public boolean onCreate() {
        return true;
    }

    @Override
    public ParcelFileDescriptor openFile(Uri uri, String mode) throws FileNotFoundException {
        if (!"r".equals(mode)) {
            throw new SecurityException("Read-only provider");
        }
        Context ctx = getContext();
        if (ctx == null) {
            throw new FileNotFoundException("Context unavailable");
        }
        File deDir = ctx.createDeviceProtectedStorageContext().getFilesDir();
        File file = new File(deDir, FILE_NAME);
        if (!file.exists()) {
            file = new File(ctx.getFilesDir(), FILE_NAME);
        }
        if (!file.exists()) {
            throw new FileNotFoundException("No custom QS image stored");
        }
        return ParcelFileDescriptor.open(file, ParcelFileDescriptor.MODE_READ_ONLY);
    }

    @Override
    public Cursor query(Uri uri, String[] projection, String selection, String[] selectionArgs, String sortOrder) {
        return null;
    }

    @Override
    public String getType(Uri uri) {
        return "image/*";
    }

    @Override
    public Uri insert(Uri uri, ContentValues values) {
        return null;
    }

    @Override
    public int delete(Uri uri, String selection, String[] selectionArgs) {
        return 0;
    }

    @Override
    public int update(Uri uri, ContentValues values, String selection, String[] selectionArgs) {
        return 0;
    }
}
